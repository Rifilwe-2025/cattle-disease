def main() -> None:
    symptoms = {}
    for k in SYMPTOM_KEYS:
        symptoms[k] = {
            'en': pretty(k),
            'sn': SN.get(k, pretty(k)),
            'nd': ND.get(k, pretty(k)),
        }

    all_disease_keys = sorted(set(DISEASES_SN.keys()) | set(DISEASES_ND.keys()))
    diseases = {}
    for k in all_disease_keys:
        diseases[k] = {
            'en': pretty(k),
            'sn': DISEASES_SN.get(k, pretty(k)),
            'nd': DISEASES_ND.get(k, pretty(k)),
        }

    out = {'symptoms': symptoms, 'diseases': diseases}
    path = Path(__file__).resolve().parent / 'cattle_terms_data.json'
    path.write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding='utf-8')
    print('Wrote', path, 'symptoms', len(symptoms), 'diseases', len(diseases))


if __name__ == '__main__':
    main()
